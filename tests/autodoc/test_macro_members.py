"""Macro-generated members are filtered by provenance, not by name.

The stub's registration macro is called ``mini_component_utils``, which does
*not* match the shipped ``uvm_*_utils`` default -- so these tests pass the
pattern explicitly. That is the point of the split: the mechanism is verified
here against the cheap stub, and the assumption that the *shipped default*
matches real UVM's macros is verified in ``tests/corpus``.
"""

from __future__ import annotations

import pytest

from sphinx_systemverilog.autodoc.documenters import SvDocumenter
from tests.conftest import uvm_stub_index

MINI = ["mini_*_utils"]


class _App:
    """Minimal app stand-in: the skip/doc events are no-ops."""

    def emit(self, *args, **kwargs):
        return []

    def emit_firstresult(self, *args, **kwargs):
        return None


@pytest.fixture(scope="module")
def index():
    return uvm_stub_index("config_tb.sv", doc_style="native")


def _render(index, name, options, **kwargs):
    obj = index.get(name)
    assert obj is not None, name
    return SvDocumenter(_App(), options, "native", index=index, **kwargs).render(obj)


def _members(lines):
    """Names of the ``sv:*`` directives emitted below the top-level object."""
    out = []
    for line in lines[1:]:
        stripped = line.strip()
        if stripped.startswith(".. sv:") and "::" in stripped:
            out.append(stripped.split("::", 1)[1].strip())
    return out


# -- provenance ---------------------------------------------------------------


def test_macro_provenance_is_recorded(index):
    """``from_macros`` ends at the macro as written, which is what a user lists."""
    driver = index.get("cfg_driver")
    by_name = {c.name: c.from_macros for c in driver.children}

    assert by_name["get_type"][-1] == "mini_component_utils"
    assert by_name["type_id"][-1] == "mini_component_utils"


def test_hand_written_members_have_no_provenance(index):
    driver = index.get("cfg_driver")
    by_name = {c.name: c.from_macros for c in driver.children}

    assert by_name["n_items"] == ()
    assert by_name["build_phase"] == ()


# -- filtering ----------------------------------------------------------------


def test_matching_macro_content_is_hidden(index):
    lines = _render(
        index, "cfg_driver",
        {"members": True, "undoc-members": True}, ignore_macros=MINI,
    )
    names = " ".join(_members(lines))

    assert "get_type" not in names
    assert "type_id" not in names
    # The class's own members are untouched.
    assert "n_items" in names
    assert "build_phase" in names


def test_non_matching_macro_content_is_kept(index):
    """A macro nobody listed generates API that may well be worth reading."""
    lines = _render(
        index, "cfg_driver",
        {"members": True, "undoc-members": True}, ignore_macros=["other_*"],
    )

    assert "get_type_name" in " ".join(_members(lines))


def test_empty_list_documents_everything(index):
    lines = _render(
        index, "cfg_driver",
        {"members": True, "undoc-members": True}, ignore_macros=[],
    )

    assert "get_type_name" in " ".join(_members(lines))


def test_hidden_under_undoc_members(index):
    """``:undoc-members:`` asks for members the author wrote and did not
    document, not for the ones they never wrote."""
    lines = _render(
        index, "cfg_driver",
        {"members": True, "undoc-members": True}, ignore_macros=MINI,
    )

    assert "get_type" not in " ".join(_members(lines))


def test_macro_members_option_shows_them(index):
    lines = _render(
        index, "cfg_driver",
        {"members": True, "undoc-members": True, "macro-members": True},
        ignore_macros=MINI,
    )

    assert "get_type_name" in " ".join(_members(lines))


def test_explicit_member_list_wins(index):
    """Naming a member is an unambiguous request for it.

    ``undoc-members`` as well because the stub's macro members carry no doc
    comment, and an explicit list does not bypass *that* filter -- only the
    macro one.
    """
    lines = _render(
        index, "cfg_driver",
        {"members": ["get_type_name"], "undoc-members": True}, ignore_macros=MINI,
    )

    assert "get_type_name" in " ".join(_members(lines))


# -- the note -----------------------------------------------------------------


def test_note_reports_what_was_hidden(index):
    lines = _render(
        index, "cfg_driver",
        {"members": True, "undoc-members": True}, ignore_macros=MINI,
    )
    text = "\n".join(lines)

    assert "3 member(s) generated by the ``mini_component_utils`` macro" in text
    assert ":macro-members:" in text


def test_no_note_when_nothing_was_hidden(index):
    lines = _render(
        index, "cfg_driver",
        {"members": True, "undoc-members": True}, ignore_macros=[],
    )

    assert "generated by" not in "\n".join(lines)


def test_no_note_under_an_explicit_member_list(index):
    """The explicit list did the narrowing, so the macro filter must not claim it."""
    lines = _render(
        index, "cfg_driver", {"members": ["n_items"]}, ignore_macros=MINI,
    )

    assert "generated by" not in "\n".join(lines)


# -- UVM constructors ---------------------------------------------------------


def test_trivial_uvm_new_is_hidden(index):
    lines = _render(
        index, "cfg_driver",
        {"members": True, "undoc-members": True}, ignore_macros=MINI,
    )

    assert "new" not in [m.split("(")[0].split()[-1] for m in _members(lines)]


def test_trivial_uvm_new_shown_when_disabled(index):
    lines = _render(
        index, "cfg_driver", {"members": True, "undoc-members": True},
        ignore_macros=MINI, hide_trivial_new=False,
    )

    assert "new" in [m.split("(")[0].split()[-1] for m in _members(lines)]


def test_documented_new_is_always_shown(index):
    """A doc comment is the author saying this constructor is worth reading."""
    driver = index.get("cfg_driver")
    new = next(c for c in driver.children if c.name == "new")
    new.raw_doc = "Builds the driver and sizes its queue."
    try:
        lines = _render(
            index, "cfg_driver", {"members": True}, ignore_macros=MINI,
        )
        assert "new" in [m.split("(")[0].split()[-1] for m in _members(lines)]
    finally:
        new.raw_doc = None


def test_new_on_a_non_uvm_class_is_untouched():
    """A plain-SystemVerilog ``new`` carries the real arguments."""
    from sphinx_systemverilog.model.objects import KIND_CLASS, KIND_FUNCTION, SvObject

    cls = SvObject(kind=KIND_CLASS, name="plain_fifo")
    cls.add_child(SvObject(
        kind=KIND_FUNCTION, name="new", signature="function new(int depth)",
    ))
    doc = SvDocumenter(_App(), {"members": True, "undoc-members": True}, "native")

    assert "new" in " ".join(_members(doc.render(cls)))
