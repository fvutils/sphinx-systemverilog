"""Generate reStructuredText for SvObjects, emitting ``sv:*`` domain directives.

This is the autodoc engine: it mirrors ``sphinx.ext.autodoc`` conceptually
(member discovery + options + a docstring-processing event) but operates on the
normalized :class:`~sphinx_systemverilog.model.objects.SvObject` model rather
than live Python objects.  Output is RST text that the directive layer
nested-parses, so all rendering/cross-referencing flows through the ``sv`` domain.
"""

from __future__ import annotations

from fnmatch import fnmatch
from typing import Any, Sequence

from ..docparse import get_parser_for
from ..model.objects import SvObject
from ..model.uvm import UVM_BOILERPLATE_MACROS

INDENT = "   "

#: Directive option lines emitted for an object, by attribute.
_MEMBER_ORDERS = ("source", "alpha", "groups")


class SvDocumenter:
    """Render one :class:`SvObject` (and, optionally, its members) to RST."""

    def __init__(
        self,
        app: Any,
        options: dict[str, Any],
        default_style: str,
        index: Any = None,
        ignore_macros: Sequence[str] | None = None,
        hide_trivial_new: bool = True,
    ):
        self.app = app
        self.options = options
        self.default_style = default_style
        self.index = index
        #: Globs matched against member provenance; see ``sv_ignore_macro_content``.
        self.ignore_macros = tuple(
            UVM_BOILERPLATE_MACROS if ignore_macros is None else ignore_macros
        )
        self.hide_trivial_new = hide_trivial_new
        #: ``_uvm_role`` walks the ``extends`` chain, and ``_skip_member`` asks
        #: for the same parent's role once per member.  Memoized per documenter.
        self._role_cache: dict[int, str] = {}

    # -- public ---------------------------------------------------------------

    def render(self, obj: SvObject, level: int = 0) -> list[str]:
        lines: list[str] = []
        indent = INDENT * level
        directive = f".. sv:{obj.kind}:: {obj.signature or obj.name}"
        lines.append(indent + directive)

        for opt in self._option_lines(obj):
            lines.append(indent + INDENT + opt)
        lines.append("")

        for doc_line in self._doc_lines(obj):
            lines.append((indent + INDENT + doc_line).rstrip())
        lines.append("")

        if obj.kind == "class" and self.options.get("show-inheritance"):
            qn = obj.qualified_name or obj.name
            lines.append(f"{indent}{INDENT}.. sv:inheritance-diagram:: {qn}")
            lines.append("")

        lines.extend(self._structure_lines(obj, indent))

        if self._wants_members(obj):
            ordered = self._ordered_members(obj)
            shown = [c for c in ordered if not self._skip_member(obj, c)]
            lines.extend(self._render_members(shown, indent, level))
            lines.extend(self._macro_note(obj, ordered, shown, indent))
            lines.extend(self._render_inherited(obj, indent, level))
        return lines

    def _macro_note(
        self,
        obj: SvObject,
        ordered: list[SvObject],
        shown: list[SvObject],
        indent: str,
    ) -> list[str]:
        """Say what the macro filter removed, keyed on the macro as written.

        Silent truncation would read as "this class has no factory registration".
        Reported the same way hidden TLM ports are, and for the same reason: the
        member is absent from the page, not from the class.
        """
        members = self.options.get("members")
        if isinstance(members, (list, tuple)) and members:
            # An explicit list is itself a statement of what the page shows, and
            # the macro filter is bypassed for it, so it did not do the
            # narrowing and saying so would be false.
            return []
        # Identity, not equality: SvObject compares by field, and two members
        # can legitimately be field-equal.
        shown_ids = {id(c) for c in shown}
        hidden = [
            c for c in ordered
            if id(c) not in shown_ids and self._is_ignored_macro_content(c)
        ]
        if not hidden:
            return []
        # The outermost name is the one in the source; several macros can
        # contribute to one class, so report the set.
        macros = sorted({c.from_macros[-1] for c in hidden if c.from_macros})
        body = indent + INDENT
        return [
            f"{body}.. note::",
            "",
            # No leading tick on the macro name: reST does not process
            # backslash escapes inside an inline literal, so ``\`x`` would
            # render the backslash.
            f"{body}{INDENT}{len(hidden)} member(s) generated by the "
            + ", ".join(f"``{m}``" for m in macros)
            + f" macro{'s' if len(macros) > 1 else ''} are not documented. "
            "Add ``:macro-members:`` to show them.",
            "",
        ]

    #: ``:show-*:`` option -> (structural directive, section heading).  Emitted
    #: as nested directives so the structural renderers stay in one place and
    #: the standalone ``sv:instance-tree::`` form behaves identically.
    _STRUCTURE_SECTIONS = (
        ("show-instances", "instance-tree", "Instance tree"),
        ("show-used-by", "used-by", "Instantiated by"),
        ("show-parameters-used", "parameter-matrix", "Parameter values used"),
    )

    #: Kinds that can participate in an elaborated hierarchy.
    _STRUCTURAL_KINDS = {"module", "interface", "program"}

    def _structure_lines(self, obj: SvObject, indent: str) -> list[str]:
        """Nested structural views for a module, when explicitly asked for.

        Every one of these triggers the instance-hierarchy walk, which is why
        none of them defaults to on.  A user who wants them everywhere can say
        so through ``sv_default_options`` --- that is their explicit choice.
        """
        if obj.kind not in self._STRUCTURAL_KINDS:
            return []
        lines: list[str] = []
        body = indent + INDENT
        for option, directive, heading in self._STRUCTURE_SECTIONS:
            if not self.options.get(option):
                continue
            lines.append(f"{body}.. rubric:: {heading}")
            lines.append("")
            lines.append(f"{body}.. sv:{directive}:: {obj.name}")
            lines.append("")
        return lines

    def _render_inherited(
        self, obj: SvObject, indent: str, level: int
    ) -> list[str]:
        if obj.kind != "class" or not self.options.get("inherited-members"):
            return []
        if self.index is None or not obj.extends:
            return []
        lines: list[str] = []
        member_indent = indent + INDENT
        own = {c.name for c in obj.children}
        seen = set(own)
        base_name = obj.extends
        while base_name:
            base = self.index.get(base_name)
            if base is None:
                break
            inherited = [
                c for c in base.children
                if c.name not in seen and not self._skip_member(base, c)
            ]
            seen.update(c.name for c in base.children)
            if inherited:
                lines.append(f"{member_indent}.. rubric:: Inherited from {base.name}")
                lines.append("")
                for child in inherited:
                    lines.extend(self.render(child, level + 1))
            base_name = base.extends
        return lines

    def _render_members(
        self, members: list[SvObject], indent: str, level: int
    ) -> list[str]:
        lines: list[str] = []
        member_indent = indent + INDENT
        current_group = object()  # sentinel distinct from any real group
        grouped = any(m.group for m in members)
        for child in members:
            if grouped and child.group != current_group:
                current_group = child.group
                if current_group:
                    lines.append(f"{member_indent}.. rubric:: {current_group}")
                    lines.append("")
            lines.extend(self.render(child, level + 1))
        return lines

    # -- options & docs -------------------------------------------------------

    #: Kinds whose signature already embeds type/direction, so qualifiers are
    #: not emitted separately to avoid duplication.
    _SELF_DESCRIBING = {"port", "parameter", "typedef"}

    def _option_lines(self, obj: SvObject) -> list[str]:
        opts: list[str] = []
        module = _module_of(obj)
        if module:
            opts.append(f":module: {module}")
        if obj.kind not in self._SELF_DESCRIBING:
            quals = [q for q in obj.qualifiers if q != "virtual"]
            if "virtual" in obj.qualifiers:
                opts.append(":virtual:")
            if quals:
                opts.append(":qualifiers: " + " ".join(quals))
        if obj.extends:
            opts.append(f":extends: {obj.extends}")
        role = self._uvm_role(obj)
        if role:
            opts.append(f":uvm: {role}")
            phases = self._uvm_phases(obj)
            if phases:
                opts.append(":phases: " + ", ".join(phases))
        if obj.location and obj.location.is_valid:
            opts.append(f":source: {obj.location.file}:{obj.location.line}")
        return opts

    def _uvm_role(self, obj: SvObject) -> str:
        """``component`` / ``sequence`` / ... for a class, else ``""``.

        The question a reader arriving on a class page asks first, and one they
        otherwise answer by following ``extends`` up three or four levels into
        the library.

        Computed from the *stored* ``extends`` chain rather than from the live
        compilation, which is what lets it survive a pickled index: this runs on
        names, and the names are in the index. It also means no UVM directive
        has to be on the page and no provider is consulted --- a class page pays
        nothing beyond a few dictionary lookups.
        """
        from ..model.uvm import uvm_role

        if obj.kind != "class" or self.index is None:
            return ""
        chain, name, seen = [obj.name], obj.extends, {obj.name}
        # Bounded: a broken index could in principle describe a cycle, and a
        # documentation build must not hang on one.
        while name and name not in seen and len(chain) < 32:
            chain.append(name)
            seen.add(name)
            base = self.index.get(name)
            name = base.extends if base is not None else ""
        return uvm_role(chain)

    def _uvm_phases(self, obj: SvObject) -> list[str]:
        """The standard phases this class implements, in execution order.

        Its *own* members only. A UVM component inherits every phase method and
        overrides two or three, so listing the inherited ones would say the same
        thing about every component in the testbench and answer nothing.
        """
        from ..model.uvm import phase_inventory

        return phase_inventory(
            child.name for child in obj.children
            if child.kind in ("function", "task")
        )

    def _doc_lines(self, obj: SvObject) -> list[str]:
        # The directive's resolved style (its :doc-style: override or the global
        # default) wins; the object's stored style is only a fallback.
        style = self.default_style or obj.doc_style
        parser = get_parser_for(style, obj.raw_doc or "")
        parsed = parser.parse(obj.raw_doc or "")
        lines = parsed.as_rst()
        # Allow user post-processing (mirrors autodoc-process-docstring).
        result = self.app.emit_firstresult(
            "sv-autodoc-process-doc", obj.kind, obj.qualified_name or obj.name,
            obj, self.options, lines,
        )
        if isinstance(result, list):
            lines = result
        return lines

    # -- member handling ------------------------------------------------------

    def _wants_members(self, obj: SvObject) -> bool:
        if not obj.is_scope or not obj.children:
            return False
        return self.options.get("members") is not None

    def _ordered_members(self, obj: SvObject) -> list[SvObject]:
        order = self.options.get("member-order", "source")
        members = list(obj.children)
        if order == "alpha":
            members.sort(key=lambda m: m.name)
        elif order == "groups":
            members.sort(key=lambda m: (m.group or "", m.location.line if m.location else 0))
        # 'source' keeps the builder's line-sorted order.
        return members

    def _skip_member(self, parent: SvObject, child: SvObject) -> bool:
        members = self.options.get("members")
        # An explicit member list restricts output to those names -- and, being
        # explicit, overrides both filters below: naming ``get_type`` is an
        # unambiguous request for it.
        named = isinstance(members, (list, tuple)) and bool(members)
        if named and child.name not in members:
            return True
        if child.name in (self.options.get("exclude-members") or ()):
            return True
        if not named and (
            self._is_ignored_macro_content(child) or self._is_trivial_uvm_new(parent, child)
        ):
            # Not folded into ``default_skip``: boilerplate stays hidden even
            # under :undoc-members:, which asks for the members the author wrote
            # and did not document, not for the ones they never wrote.
            return self._emit_skip(parent, child, True)
        # Undocumented leaf members are hidden unless :undoc-members: is set.
        # Ports, parameters and coverpoints are structural API and always shown.
        structural = child.kind in ("port", "parameter", "coverpoint")
        default_skip = (
            not child.is_documented
            and not child.is_scope
            and not structural
            and not self.options.get("undoc-members")
        )
        return self._emit_skip(parent, child, default_skip)

    def _is_ignored_macro_content(self, child: SvObject) -> bool:
        """True if *child* was generated by a macro the project ignores."""
        if self.options.get("macro-members") or not child.from_macros:
            return False
        return any(
            fnmatch(name, pattern)
            for name in child.from_macros
            for pattern in self.ignore_macros
        )

    def _is_trivial_uvm_new(self, parent: SvObject, child: SvObject) -> bool:
        """True for an undocumented constructor on a UVM class.

        UVM dictates the signature, so such a ``new`` says only what ``:uvm:``
        already says. A documented one is the author telling us otherwise.
        """
        if not self.hide_trivial_new or child.name != "new" or child.is_documented:
            return False
        return bool(self._cached_uvm_role(parent))

    def _cached_uvm_role(self, obj: SvObject) -> str:
        key = id(obj)
        if key not in self._role_cache:
            self._role_cache[key] = self._uvm_role(obj)
        return self._role_cache[key]

    def _emit_skip(self, parent: SvObject, child: SvObject, default: bool) -> bool:
        results = self.app.emit(
            "sv-autodoc-skip-member", child.kind,
            child.qualified_name or child.name, child, self.options, default,
        )
        for r in results:
            if r is not None:
                return bool(r)
        return default


def _module_of(obj: SvObject) -> str | None:
    qn = obj.qualified_name
    if not qn or "::" not in qn:
        return None
    return qn.rsplit("::", 1)[0]
