"""Configuration values for the sphinx-systemverilog extension.

All ``sv_*`` configuration values are registered here via :func:`register_config`,
which is called from :func:`sphinx_systemverilog.setup`.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from .model.uvm import DEFAULT_BLACKBOX_BASES, UVM_BOILERPLATE_MACROS

if TYPE_CHECKING:
    from sphinx.application import Sphinx


#: Valid values for ``sv_doc_style``.
DOC_STYLES = ("native", "naturaldocs", "doxygen", "auto")


def register_config(app: "Sphinx") -> None:
    """Register all ``sv_*`` configuration values on the Sphinx application."""
    # Directories scanned to build the project-wide source index.
    app.add_config_value("sv_source_dirs", [], "env", types=[list])
    # Additional include directories passed to the pyslang preprocessor.
    app.add_config_value("sv_include_dirs", [], "env", types=[list])
    # Preprocessor ``define`` values (name -> value) for elaboration.
    app.add_config_value("sv_defines", {}, "env", types=[dict])
    # Explicit "build unit" roots to elaborate (e.g. ["uvm_pkg.sv"]).
    app.add_config_value("sv_build_units", [], "env", types=[list])
    # Default doc-comment dialect: one of DOC_STYLES.
    app.add_config_value("sv_doc_style", "native", "env", types=[str])
    # How to treat UVM ``-- NODOCS --`` blocks: "include" the prose or "skip".
    app.add_config_value("sv_naturaldocs_nodocs", "include", "env", types=[str])
    # Default options applied to every auto* directive (e.g. {"members": True}).
    app.add_config_value("sv_default_options", {}, "env", types=[dict])
    # Generate '[source]' links to highlighted SystemVerilog source.
    app.add_config_value("sv_viewcode", True, "env", types=[bool])
    # Extract and document `\`define` macros.
    app.add_config_value("sv_document_macros", True, "env", types=[bool])
    # Glob patterns matched against the macro-expansion chain of every class
    # member.  A match means the member was generated by registration
    # boilerplate rather than authored, and is not documented: `\`uvm_*_utils`
    # puts ``get_type``/``create``/``get_type_name`` in *every* registered
    # class, and their prose is the same each time, so listing them buries the
    # handful of methods the class actually adds.  Not a blanket "hide macro
    # content" switch --- a project's own declaration macros may well generate
    # the API worth reading --- so it is a list, defaulting to UVM's.
    # ``:macro-members:`` on a directive shows them anyway.
    app.add_config_value(
        "sv_ignore_macro_content", list(UVM_BOILERPLATE_MACROS), "env", types=[list]
    )
    # Document a UVM class's `new` only when it carries a doc comment of its own.
    # UVM fixes the constructor signature --- ``(string name, uvm_component
    # parent)`` --- so an undocumented one adds nothing a reader cannot infer
    # from the class being a component.  Hand-written, so the macro list above
    # cannot reach it, and scoped to UVM classes so a plain-SystemVerilog
    # project (where `new` carries the real arguments) is unaffected.
    app.add_config_value("sv_uvm_hide_trivial_new", True, "env", types=[bool])
    # Restrict the (lazy) instance-hierarchy walk to these top modules.
    # Empty = every elaborated top.  Only consulted when a structural directive
    # actually asks for the hierarchy.
    app.add_config_value("sv_structure_tops", [], "env", types=[list])
    # Ceiling on instances visited during a hierarchy walk; exceeding it reports
    # truncation rather than letting a pathological generate loop hang a build.
    app.add_config_value("sv_structure_max_instances", 20000, "env", types=[int])
    # Default depth for ``sv:instance-tree``.  A real SoC tree is thousands of
    # nodes, so the default shows the shape rather than the whole thing.
    app.add_config_value("sv_instance_tree_depth", 3, "env", types=[int])
    # Cap on instantiation sites listed by ``sv:used-by``; the elided count is
    # always reported.  0 disables the cap.
    app.add_config_value("sv_used_by_limit", 50, "env", types=[int])

    # -- UVM testbench elaboration -------------------------------------------
    # Glob patterns matched against a component's type name.  A match is
    # rendered as an *opaque* node -- present, labelled and counted, never
    # dropped.  This is how a testbench documents cleanly when part of it does
    # not exist at doc-generation time (a RAL package generated from RDL, a
    # vendor VIP delivered as an encrypted library).
    app.add_config_value("sv_uvm_blackbox", [], "env", types=[list])
    # As above, but matched against the base-class chain, so one entry covers a
    # whole family.  The default lives in ``model.uvm`` so the shipped default
    # and the one ``build_index`` applies cannot drift apart.
    app.add_config_value(
        "sv_uvm_blackbox_bases", list(DEFAULT_BLACKBOX_BASES), "env", types=[list]
    )
    # Root component to elaborate from.  Empty = auto-detect via the
    # ``run_test("...")`` argument in a top module.
    app.add_config_value("sv_uvm_root", "", "env", types=[str])
    # Default depth for ``sv:uvm-tree``.  Deeper than the RTL default because a
    # testbench is naturally shallower: test -> env -> agent -> driver is 4.
    app.add_config_value("sv_uvm_tree_depth", 4, "env", types=[int])
    # Ceiling on components visited during a testbench walk, mirroring
    # ``sv_structure_max_instances``.  Exceeding it reports truncation.
    app.add_config_value("sv_uvm_max_components", 5000, "env", types=[int])
    # Promote orphaned ``config_db`` settings to build warnings.  Off by
    # default, and deliberately so: adopting this extension must not turn a
    # green build red because of a testbench smell nobody asked about.  The
    # finding is always rendered in the page; escalating it is a project's own
    # decision, taken once, in writing.
    app.add_config_value("sv_uvm_warn_orphans", False, "env", types=[bool])


def validate_config(app: "Sphinx", config) -> None:
    """Validate ``sv_*`` config values; emit a warning for bad input.

    Connected to the ``config-inited`` event.
    """
    from sphinx.util import logging

    logger = logging.getLogger(__name__)
    for name, default, allow_zero in (
        ("sv_structure_max_instances", 20000, False),
        ("sv_instance_tree_depth", 3, False),
        ("sv_used_by_limit", 50, True),      # 0 means "no cap"
        ("sv_uvm_tree_depth", 4, False),
        ("sv_uvm_max_components", 5000, False),
    ):
        value = getattr(config, name, default)
        floor = 0 if allow_zero else 1
        if not isinstance(value, int) or isinstance(value, bool) or value < floor:
            logger.warning(
                "%s must be an integer >= %d, not %r; falling back to %d",
                name, floor, value, default, type="systemverilog",
            )
            setattr(config, name, default)
    if config.sv_doc_style not in DOC_STYLES:
        logger.warning(
            "sv_doc_style %r is not one of %s; falling back to 'native'",
            config.sv_doc_style,
            ", ".join(DOC_STYLES),
            type="systemverilog",
        )
        config.sv_doc_style = "native"
